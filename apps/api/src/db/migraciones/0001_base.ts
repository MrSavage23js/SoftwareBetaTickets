export async function up(db: Kysely<unknown>): Promise<void> {
  for (const s of [...PREPARACION, ...TABLAS_SQL]) await sql.raw(s).execute(db);
  for (const t of CON_ACTUALIZADO) {
    await sql.raw(`CREATE TRIGGER tr_${t}_actualizado BEFORE UPDATE ON ${t} FOR EACH ROW EXECUTE FUNCTION fijar_actualizado_at()`).execute(db);
  }
}

