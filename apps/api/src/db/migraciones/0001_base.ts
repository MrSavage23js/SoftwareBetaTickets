// Reúne en una sola lo que en MySQL fueron las migraciones 0001 a 0007 (siguen en el historial de git).
// Reglas: las migraciones solo avanzan; nunca se edita una que ya corrió en producción, se agrega otra.
//
// Equivalencias con lo que hacía MySQL:
//   - utf8mb4_0900_ai_ci (sin distinguir mayúsculas ni acentos) → intercalación ICU `sin_acentos` en los
//     textos que se comparan con "=" o deben ser únicos (usuario, correo, nombres de catálogos).
//     Las búsquedas con LIKE usan f_unaccent(…) ILIKE (ver lib/buscar.ts).
//   - FULLTEXT → columna `busqueda` (tsvector) calculada sola, con índice GIN.
//   - ON UPDATE CURRENT_TIMESTAMP → disparador que actualiza `actualizado_at`.
//   - DATETIME(3) en UTC → TIMESTAMPTZ(3).  JSON → JSONB.  TINYINT(1) → BOOLEAN.
